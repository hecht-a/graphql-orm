<?php

declare(strict_types=1);

namespace GraphqlOrm\Codegen;

use GraphqlOrm\Metadata\GraphqlEntityMetadata;
use GraphqlOrm\Query\Expr\ExpressionBuilder;
use GraphqlOrm\Query\GraphqlQueryBuilder;
use GraphqlOrm\Repository\GraphqlEntityRepository;

/**
 * Writes the PhpStorm metadata completing the field names given to the query builder, the expressions and the
 * repositories: the fields of every entity, or those of its entity on a repository of its own.
 *
 * @see https://www.jetbrains.com/help/phpstorm/ide-advanced-metadata.html
 *
 * @internal
 */
final class PhpstormMetaGenerator
{
    private const FIELDS = 'graphql_orm_fields';
    private const PATHS = 'graphql_orm_paths';
    private const RELATIONS = 'graphql_orm_relations';

    /** The arguments of the query builder taking fields, by method: the argument set and the positions. */
    private const QUERY_BUILDER_ARGUMENTS = [
        'orderBy' => [self::FIELDS, [0]],
        'indexBy' => [self::FIELDS, [0]],
        'addSelect' => [self::PATHS, [0]],
        'select' => [self::PATHS, [0, 1, 2, 3, 4]],
        'with' => [self::RELATIONS, [0, 1, 2, 3, 4]],
    ];

    /** The argument of findBy() keying the result. */
    private const INDEX_BY_POSITION = 3;

    /**
     * @param list<class-string>                            $entityClasses
     * @param \Closure(class-string): GraphqlEntityMetadata $metadata      the mapping of an entity, read by its manager
     */
    public function generate(array $entityClasses, \Closure $metadata): string
    {
        $fields = [];
        $paths = [];
        $relations = [];
        $repositories = [];

        foreach ($entityClasses as $class) {
            $entity = $metadata($class);
            $entityFields = [];

            foreach ($entity->fields as $field) {
                $entityFields[] = $field->property;

                if ($field->relation === null) {
                    continue;
                }

                $relations[] = $field->property;

                foreach ($metadata($field->relation)->fields as $nested) {
                    $paths[] = $field->property . '.' . $nested->property;

                    if ($nested->relation !== null) {
                        $relations[] = $field->property . '.' . $nested->property;
                    }
                }
            }

            $fields = [...$fields, ...$entityFields];

            if ($entity->repositoryClass !== null) {
                $repositories[$entity->repositoryClass] = [self::FIELDS . '_' . str_replace('\\', '_', $class), $entityFields];
            }
        }

        $lines = [
            self::argumentsSet(self::FIELDS, $fields),
            self::argumentsSet(self::PATHS, [...$fields, ...$paths]),
            self::argumentsSet(self::RELATIONS, $relations),
            '',
        ];

        foreach (self::QUERY_BUILDER_ARGUMENTS as $method => [$set, $positions]) {
            foreach ($positions as $position) {
                $lines[] = self::expectedArguments(GraphqlQueryBuilder::class, $method, $position, $set);
            }
        }

        foreach (self::methodsTakingAField(ExpressionBuilder::class) as $method) {
            $lines[] = self::expectedArguments(ExpressionBuilder::class, $method, 0, self::PATHS);
        }

        $lines = [...$lines, ...self::repositoryArguments(GraphqlEntityRepository::class, self::FIELDS)];

        foreach ($repositories as $repositoryClass => [$set, $entityFields]) {
            $lines[] = '';
            $lines[] = self::argumentsSet($set, $entityFields);
            $lines = [...$lines, ...self::repositoryArguments($repositoryClass, $set)];
        }

        return "<?php\n\n"
            . "// Generated by graphqlorm:phpstorm-meta: the field names of the GraphQL entities, completed by PhpStorm.\n"
            . "// Run it again after changing the mapping.\n\n"
            . "namespace PHPSTORM_META {\n"
            . implode("\n", array_map(static fn (string $line): string => $line === '' ? '' : '    ' . $line, $lines))
            . "\n}\n";
    }

    /**
     * @return list<string>
     */
    private static function repositoryArguments(string $repositoryClass, string $set): array
    {
        $lines = [];

        foreach (self::methodsTakingAField(GraphqlEntityRepository::class) as $method) {
            $lines[] = self::expectedArguments($repositoryClass, $method, 0, $set);
        }

        $lines[] = self::expectedArguments($repositoryClass, 'findBy', self::INDEX_BY_POSITION, $set);

        return $lines;
    }

    /**
     * The public methods whose first parameter is a field: `string $field`.
     *
     * @param class-string $class
     *
     * @return list<string>
     */
    private static function methodsTakingAField(string $class): array
    {
        $methods = [];

        foreach ((new \ReflectionClass($class))->getMethods(\ReflectionMethod::IS_PUBLIC) as $method) {
            if (($method->getParameters()[0] ?? null)?->getName() === 'field') {
                $methods[] = $method->getName();
            }
        }

        return $methods;
    }

    /**
     * @param list<string> $values
     */
    private static function argumentsSet(string $name, array $values): string
    {
        $values = array_values(array_unique($values));
        sort($values);

        return \sprintf('registerArgumentsSet(%s);', implode(', ', array_map(self::quote(...), [$name, ...$values])));
    }

    private static function expectedArguments(string $class, string $method, int $position, string $set): string
    {
        return \sprintf('expectedArguments(\\%s::%s(), %d, argumentsSet(%s));', $class, $method, $position, self::quote($set));
    }

    private static function quote(string $value): string
    {
        return "'" . addcslashes($value, "'\\") . "'";
    }
}
